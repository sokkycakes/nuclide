#!/usr/bin/env python3
"""Writes out/gen/steam_input_data.c: the launcher's Steam Input action
manifest, a default layout per controller type, and the button prompts it
draws (Xelu's, CC0, from src/glyphs/<set>/<button>.png).

The launcher writes the manifest and layouts into <install dir>/.launcher/
steam_input/ when it starts and points Steam at them
(SetInputActionManifestFilePath), so the release stays one executable.

The layout files follow the controller_mappings format Steam exports
(steam://dumpcontrollerconfig?appid=480). They are the same shape as
Bulwark's (bulwark-engine tools/steaminput/gen_configs.py).

    python3 tools/gen_steam_input.py out/gen/steam_input_data.c
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(os.path.dirname(HERE), 'src')

# one action set; action names must match src/input_steam.c
ANALOG = [
    ('ui_move', 'Move', 'joystick_move'),
    ('ui_scroll', 'Scroll the notes', 'joystick_move'),
]
BUTTONS = [
    ('ui_up', 'Up'),
    ('ui_down', 'Down'),
    ('ui_select', 'Select'),
    ('ui_back', 'Quit'),
    ('ui_play', 'Play'),
    ('ui_notes_up', 'Notes up'),
    ('ui_notes_down', 'Notes down'),
]
SET = 'Launcher'
# physical button (by position) -> action
LAYOUT = {
    'south': 'ui_select', 'east': 'ui_back', 'start': 'ui_play',
    'dup': 'ui_up', 'ddown': 'ui_down', 'lb': 'ui_notes_up', 'rb': 'ui_notes_down',
    'lstick': 'ui_move', 'rstick': 'ui_scroll', 'rpad': 'ui_scroll',
}
# controller type -> what it has (the original Steam Controller has no right
# stick and a left trackpad in place of the d-pad)
CONTROLLERS = {
    'controller_neptune': {'title': 'Steam Deck', 'rstick': True, 'rpad': False, 'dpad': 'dpad'},
    'controller_steamcontroller_gordon': {'title': 'Steam Controller', 'rstick': False, 'rpad': True,
                                          'dpad': 'left_trackpad'},
    'controller_xboxone': {'title': 'Xbox', 'rstick': True, 'rpad': False, 'dpad': 'dpad'},
    'controller_xbox360': {'title': 'Xbox 360', 'rstick': True, 'rpad': False, 'dpad': 'dpad'},
    'controller_ps4': {'title': 'PlayStation 4', 'rstick': True, 'rpad': False, 'dpad': 'dpad'},
    'controller_ps5': {'title': 'PlayStation 5', 'rstick': True, 'rpad': False, 'dpad': 'dpad'},
    'controller_switch_pro': {'title': 'Switch Pro', 'rstick': True, 'rpad': False, 'dpad': 'dpad'},
    'controller_generic': {'title': 'Gamepad', 'rstick': True, 'rpad': False, 'dpad': 'dpad'},
}
# glyph sets and buttons, in the order of si_set_t and si_button_t's names
GLYPH_SETS = ['xbox', 'xbox360', 'ps4', 'ps5', 'switch', 'steamdeck', 'steamcontroller']
GLYPH_BUTTONS = ['south', 'east', 'start', 'dpad', 'lb', 'rb', 'rstick']


def q(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


class VDF:
    def __init__(self):
        self.lines = []
        self.depth = 0

    def kv(self, k, v):
        self.lines.append('\t' * self.depth + q(k) + '\t\t' + q(str(v)))

    def open(self, k):
        self.lines.append('\t' * self.depth + q(k))
        self.lines.append('\t' * self.depth + '{')
        self.depth += 1

    def close(self):
        self.depth -= 1
        self.lines.append('\t' * self.depth + '}')

    def text(self):
        return '\n'.join(self.lines) + '\n'


def write_actions(v):
    v.open('actions')
    v.open(SET)
    v.kv('title', '#Set_' + SET)
    v.kv('legacy_set', '0')
    v.open('StickPadGyro')
    for a, t, mode in ANALOG:
        v.open(a)
        v.kv('title', '#Action_' + a)
        v.kv('input_mode', mode)
        v.close()
    v.close()
    v.open('Button')
    for a, t in BUTTONS:
        v.kv(a, '#Action_' + a)
    v.close()
    v.close()
    v.close()


def write_localization(v):
    v.open('localization')
    v.open('english')
    v.kv('title', 'Playtest launcher')
    v.kv('description', 'Playtest launcher controls')
    v.kv('Set_' + SET, 'Launcher')
    for a, t, *_ in ANALOG + BUTTONS:
        v.kv('Action_' + a, t)
    v.close()
    v.close()


def layout_name(ctype):
    return 'launcher_%s.vdf' % ctype.replace('controller_', '')


def manifest():
    v = VDF()
    v.lines.append('// Playtest launcher Steam Input actions. Generated by tools/gen_steam_input.py.')
    v.open('Action Manifest')
    v.open('configurations')
    for ctype in CONTROLLERS:
        v.open(ctype)
        v.open('0')
        v.kv('path', layout_name(ctype))
        v.close()
        v.close()
    v.close()
    write_actions(v)
    write_localization(v)
    v.close()
    return v.text()


def config(ctype, caps):
    v = VDF()
    groups = []

    def group(mode, inputs, source, gameaction=None):
        gid = len(groups)
        v.open('group')
        v.kv('id', gid)
        v.kv('mode', mode)
        v.kv('name', '')
        v.kv('description', '')
        v.open('inputs')
        for inp, action in inputs:
            if not action:
                continue
            v.open(inp)
            v.open('activators')
            v.open('Full_Press')
            v.open('bindings')
            v.kv('binding', 'game_action %s %s, , ' % (SET, action))
            v.close()
            v.close()
            v.close()
            v.close()
        v.close()
        if gameaction:
            v.open('gameactions')
            v.kv(SET, gameaction)
            v.close()
        v.close()
        groups.append((gid, source))

    lay = LAYOUT
    v.lines.append('// Playtest launcher layout for %s. Generated by tools/gen_steam_input.py.' % caps['title'])
    v.open('controller_mappings')
    for k, val in [('version', '3'), ('revision', '1'), ('title', '#title'), ('description', '#description'),
                   ('creator', ''), ('progenitor', ''), ('url', ''), ('export_type', 'unknown'),
                   ('controller_type', ctype), ('major_revision', '0'), ('minor_revision', '0'),
                   ('Timestamp', '0')]:
        v.kv(k, val)
    write_actions(v)
    write_localization(v)
    group('four_buttons', [('button_a', lay.get('south')), ('button_b', lay.get('east'))], 'button_diamond')
    group('dpad', [('dpad_north', lay.get('dup')), ('dpad_south', lay.get('ddown'))], caps['dpad'])
    group('joystick_move', [], 'joystick', lay.get('lstick'))
    group('switches', [('left_bumper', lay.get('lb')), ('right_bumper', lay.get('rb')),
                       ('button_escape', lay.get('start'))], 'switch')
    if caps['rstick']:
        group('joystick_move', [], 'right_joystick', lay.get('rstick'))
    if caps['rpad']:
        group('joystick_move', [], 'right_trackpad', lay.get('rpad'))
    v.open('preset')
    v.kv('id', 0)
    v.kv('name', SET)
    v.open('group_source_bindings')
    for g, source in groups:
        v.kv(str(g), source + ' active')
    v.close()
    v.close()
    v.open('settings')
    v.close()
    v.close()
    return v.text()


def c_string(name, text):
    out = ['static const char %s[] =' % name]
    for line in text.splitlines(True):
        out.append('\t' + q(line).replace('\n', '\\n'))
    return '\n'.join(out) + ';\n'


def c_bytes(name, data):
    out = ['static const unsigned char %s[%d] = {' % (name, len(data))]
    for i in range(0, len(data), 24):
        out.append(','.join(str(b) for b in data[i:i + 24]) + ',')
    return '\n'.join(out) + '};\n'


def main():
    out_path = sys.argv[1]
    parts = ['/* generated by tools/gen_steam_input.py, do not edit */',
             '#include <stddef.h>', '#include "input_steam_data.h"', '']
    parts.append(c_string('manifest', manifest()))
    files = [('steam_input_manifest.vdf', 'manifest')]
    for i, (ctype, caps) in enumerate(CONTROLLERS.items()):
        parts.append(c_string('layout%d' % i, config(ctype, caps)))
        files.append((layout_name(ctype), 'layout%d' % i))
    parts.append('const steam_input_file steam_input_files[] = {')
    for name, var in files:
        parts.append('\t{"%s", %s},' % (name, var))
    parts.append('\t{NULL, NULL}};\n')
    table = []
    for s, setname in enumerate(GLYPH_SETS):
        row = []
        for b, btn in enumerate(GLYPH_BUTTONS):
            path = os.path.join(SRC, 'glyphs', setname, btn + '.png')
            if os.path.exists(path):
                var = 'g_%s_%s' % (setname, btn)
                data = open(path, 'rb').read()
                parts.append(c_bytes(var, data))
                row.append('{%s, %d}' % (var, len(data)))
            else:
                row.append('{NULL, 0}')
        table.append('\t{' + ', '.join(row) + '},')
    parts.append('const steam_input_png steam_input_glyphs[SIG_SETS][SIG_BUTTONS] = {')
    parts += table
    parts.append('};')
    os.makedirs(os.path.dirname(os.path.abspath(out_path)), exist_ok=True)
    with open(out_path, 'w', newline='\n') as f:
        f.write('\n'.join(parts) + '\n')


if __name__ == '__main__':
    main()
