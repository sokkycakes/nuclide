#!/usr/bin/env python3
"""Writes a C file holding the two default UI fonts as byte arrays."""
import sys

def emit(out, name, path):
    data = open(path, 'rb').read()
    out.write(f'const unsigned int {name}_len = {len(data)};\n')
    out.write(f'const unsigned char {name}[] = {{\n')
    for i in range(0, len(data), 24):
        out.write(','.join(str(b) for b in data[i:i + 24]) + ',\n')
    out.write('0};\n')

with open(sys.argv[1], 'w') as out:
    out.write('/* generated by tools/embed_font.py, do not edit */\n')
    emit(out, 'font_regular', sys.argv[2])
    emit(out, 'font_bold', sys.argv[3])
